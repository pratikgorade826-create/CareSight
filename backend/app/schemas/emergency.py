from datetime import datetime
from typing import Optional, List, Dict, Any, Literal
from pydantic import BaseModel, Field

class LocationPayload(BaseModel):
    lat: Optional[float] = None
    lng: Optional[float] = None
    address: Optional[str] = "Current detected location"

class EmergencyContactCreate(BaseModel):
    elderly_user_id: Optional[str] = None
    name: str = Field(min_length=1)
    relationship: str = Field(min_length=1)
    phone_number: str = Field(min_length=7)
    priority_order: int = 1
    is_notified_on_sos: bool = True

class EmergencyContactResponse(EmergencyContactCreate):
    id: str
    elderly_user_id: str
    created_at: datetime

class SOSTriggerRequest(BaseModel):
    elderly_user_id: Optional[str] = None
    location: Optional[LocationPayload] = None
    notes: Optional[str] = "Urgent emergency assistance requested via CareSight SOS"

class SOSEventResponse(BaseModel):
    id: str
    elderly_user_id: str
    triggered_by_user_id: str
    triggered_by_name: str
    location: Optional[LocationPayload] = None
    status: Literal["active", "acknowledged", "resolved"]
    notes: Optional[str] = None
    resolved_by_user_id: Optional[str] = None
    resolved_notes: Optional[str] = None
    triggered_at: datetime
    resolved_at: Optional[datetime] = None

class EmergencyCardResponse(BaseModel):
    elderly_name: str
    date_of_birth: Optional[str] = None
    blood_type: Optional[str] = None
    allergies: List[str] = Field(default_factory=list)
    chronic_conditions: List[str] = Field(default_factory=list)
    primary_contacts: List[EmergencyContactResponse] = Field(default_factory=list)
    emergency_notes: Optional[str] = None
    disclaimer: str = "This health card is generated by CareSight for coordination. In life-threatening emergencies, dial 112 / 911 immediately."
